"""The LCD's digit segments from TE's screen-layout drawing (69021d87...svg),
written as a C++ header for the display renderer (plan M9: "segment count taken
from the SVG").

TE's digit is not a 7-segment: each of the three digits has a full-height left
and right bar, a top and a bottom bar, an upper and a lower centre bar and four
shaped corner pieces (upper-left, upper-right, lower-left, lower-right), plus a
decimal point after the first two. Polygons are mapped into the display
texture's pixels (DisplayRenderer, 1024 x 289) by the digit panel's rectangle.

    python -I tools/model/artwork/lcd_segments.py > Source/Stage/LcdSegments.h
"""

import sys
from pathlib import Path

import numpy as np
from svgelements import SVG, Close, CubicBezier, Line, Move, Path as SvgPath, QuadraticBezier, Arc, Shape

SCREEN_SVG = Path(__file__).resolve().parents[3] / "reference" / "te-ep40" / "69021d87c95e942b7d172721.svg"
SEGMENT_INK = "#194824"
PANEL_INK = "#5e8270"
CURSOR_INK = "#ffffff"
# The digit panel in the display texture (halo_screen_indicators.png, px).
TEXTURE_PANEL = (447.0, 64.0, 630.0, 157.0)
NAMES = ["top", "bottom", "left", "right", "upperCentre", "lowerCentre",
         "upperLeft", "upperRight", "lowerLeft", "lowerRight"]


def flatten(sub, steps=6):
    pts = []
    for seg in sub:
        if isinstance(seg, Move):
            pts.append((seg.end.x, seg.end.y))
        elif isinstance(seg, (Line, Close)):
            if seg.end is not None:
                pts.append((seg.end.x, seg.end.y))
        elif isinstance(seg, (CubicBezier, QuadraticBezier, Arc)):
            for p in seg.npoint(np.linspace(0, 1, steps + 1)[1:]):
                pts.append((float(p[0]), float(p[1])))
    out = []
    for p in pts:   # drop repeats (closing points)
        if not out or abs(out[-1][0] - p[0]) > 1e-6 or abs(out[-1][1] - p[1]) > 1e-6:
            out.append(p)
    if len(out) > 2 and abs(out[0][0] - out[-1][0]) < 1e-6 and abs(out[0][1] - out[-1][1]) < 1e-6:
        out.pop()
    return out


def classify(bb, origin_x, top_y):
    """Which segment a subpath's bbox (x0, y0, x1, y1) is, in its digit's frame."""
    x0, y0, x1, y1 = bb[0] - origin_x, bb[1] - top_y, bb[2] - origin_x, bb[3] - top_y
    w, h = x1 - x0, y1 - y0
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    if w > 15 and h < 8:
        return "top" if cy < 20 else "bottom"
    if h > 40 and w < 8:
        return "left" if cx < 20 else "right"
    if w < 8 and 15 < h < 25:
        return "upperCentre" if cy < 29 else "lowerCentre"
    if 10 < w < 15 and 20 < h < 30:
        return ("upper" if cy < 29 else "lower") + ("Left" if cx < 19 else "Right")
    return None


def main():
    svg = SVG.parse(str(SCREEN_SVG))
    panel = None
    subs = []
    for e in svg.elements():
        if not isinstance(e, Shape):
            continue
        ink = str(e.fill).lower()
        if ink == PANEL_INK:
            panel = SvgPath(e).bbox()
        if ink in (SEGMENT_INK, CURSOR_INK):
            for s in SvgPath(e).as_subpaths():
                subs.append(SvgPath(s))
    px0, py0, px1, py1 = panel
    tx0, ty0, tx1, ty1 = TEXTURE_PANEL
    sx, sy = (tx1 - tx0) / (px1 - px0), (ty1 - ty0) / (py1 - py0)

    # Digit origins: the left bars, left to right.
    lefts = sorted({round(p.bbox()[0], 1) for p in subs if (p.bbox()[3] - p.bbox()[1]) > 40 and (p.bbox()[2] - p.bbox()[0]) < 8})
    origins = lefts[0::2]          # each digit has a left and a right full-height bar
    top_y = min(p.bbox()[1] for p in subs)
    digits = [dict() for _ in origins]
    points = []
    for p in subs:
        bb = p.bbox()
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        if w < 7 and h < 7:
            points.append(p)
            continue
        cx = (bb[0] + bb[2]) / 2
        d = max(i for i, o in enumerate(origins) if cx >= o - 1)
        name = classify(bb, origins[d], top_y)
        if name is None:
            raise SystemExit(f"unclassified segment at {bb}")
        digits[d][name] = flatten(p)
    for d, segs in enumerate(digits):
        missing = [n for n in NAMES if n not in segs]
        if missing:
            raise SystemExit(f"digit {d}: missing {missing}")

    def tex(pt):
        return (tx0 + (pt[0] - px0) * sx, ty0 + (pt[1] - py0) * sy)

    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// Generated by tools/model/artwork/lcd_segments.py from TE's screen drawing")
    out.append("// (reference/te-ep40/69021d87...svg). Do not edit: rerun the tool.")
    out.append("//")
    out.append("// Three digits of ten segments each (see Segment), and the two decimal")
    out.append("// points, as polygons in the display texture's pixels (1024 x 289).")
    out.append("")
    out.append("#include <array>")
    out.append("")
    out.append("namespace halo::lcd")
    out.append("{")
    out.append("    enum Segment : int { " + ", ".join(f"{n} = {i}" for i, n in enumerate(NAMES)) + ", segmentCount };")
    out.append("")
    out.append("    struct Point { float x, y; };")
    out.append("")
    flat, index = [], []
    for d, segs in enumerate(digits):
        for n in NAMES:
            start = len(flat)
            flat.extend(tex(p) for p in segs[n])
            index.append((start, len(flat) - start))
    dp_index = []
    for p in sorted(points, key=lambda q: q.bbox()[0]):
        start = len(flat)
        flat.extend(tex(q) for q in flatten(p))
        dp_index.append((start, len(flat) - start))
    out.append(f"    inline constexpr std::array<Point, {len(flat)}> segmentPoints {{{{")
    for i in range(0, len(flat), 4):
        out.append("        " + " ".join(f"Point {{ {x:.2f}f, {y:.2f}f }}," for x, y in flat[i:i + 4]))
    out.append("    }};")
    out.append("")
    out.append("    // [digit * segmentCount + segment] -> (first point, point count)")
    out.append(f"    inline constexpr std::array<std::array<int, 2>, {len(index)}> segmentRanges {{{{")
    for i in range(0, len(index), 5):
        out.append("        " + " ".join(f"{{ {{ {a}, {b} }} }}," for a, b in index[i:i + 5]))
    out.append("    }};")
    out.append("")
    out.append(f"    inline constexpr std::array<std::array<int, 2>, {len(dp_index)}> decimalPointRanges {{{{")
    out.append("        " + " ".join(f"{{ {{ {a}, {b} }} }}," for a, b in dp_index))
    out.append("    }};")
    out.append("")
    out.append(f"    inline constexpr int digitCount = {len(digits)};")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
